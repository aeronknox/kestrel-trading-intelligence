"""Explainable signal scoring.

A signal is a weighted average of independent components, each scored in [-1, 1]
with a human-readable reason. Nothing here is generated by an LLM.
"""

from dataclasses import asdict, dataclass

import numpy as np

from app.ai.patterns import Pattern

BUY_THRESHOLD = 0.2
SELL_THRESHOLD = -0.2
MAX_CONFIDENCE = 85.0  # never present a signal as near-certain


@dataclass
class Component:
    name: str
    score: float  # -1 (bearish) .. 1 (bullish)
    weight: float
    reason: str

    def to_dict(self) -> dict:
        return asdict(self)


def _fmt_price(v: float) -> str:
    return f"{v:,.2f}" if abs(v) >= 1 else f"{v:.6g}"


def _clip(x: float) -> float:
    return float(np.clip(x, -1.0, 1.0))


def score_components(ind: dict, trend: dict, patterns: list[Pattern], ml: dict) -> list[Component]:
    comps: list[Component] = []
    close = ind.get("close")

    # 1. Trend structure
    if close and ind.get("sma_50"):
        s = 0.0
        parts = []
        s += 0.4 if close > ind["sma_50"] else -0.4
        parts.append(f"price {'above' if close > ind['sma_50'] else 'below'} SMA50")
        if ind.get("sma_200"):
            s += 0.3 if close > ind["sma_200"] else -0.3
            s += 0.3 if ind["sma_50"] > ind["sma_200"] else -0.3
            parts.append(f"price {'above' if close > ind['sma_200'] else 'below'} SMA200")
            parts.append(f"SMA50 {'above' if ind['sma_50'] > ind['sma_200'] else 'below'} SMA200")
        reg = trend["regression_move_pct"]
        parts.append(f"{trend['lookback_bars']}-bar regression {reg:+.1f}% (R² {trend['r_squared']:.2f})")
        comps.append(Component("Trend", _clip(s), 0.25, "; ".join(parts) + "."))

    # 2. MACD momentum
    if ind.get("macd_hist") is not None and close:
        hist_n = ind["macd_hist"] / close * 100
        s = _clip(hist_n / 0.5)
        comps.append(
            Component(
                "MACD momentum",
                s,
                0.15,
                f"MACD histogram is {ind['macd_hist']:+.4g} ({'positive' if hist_n > 0 else 'negative'} momentum).",
            )
        )

    # 3. RSI (mean-reversion at extremes, mild momentum in the middle)
    r = ind.get("rsi_14")
    if r is not None:
        if r >= 70:
            s, why = -min(1.0, (r - 65) / 20), "overbought — elevated pullback risk"
        elif r <= 30:
            s, why = min(1.0, (35 - r) / 20), "oversold — elevated rebound potential"
        else:
            s, why = (r - 50) / 50, "neutral zone, mild momentum bias"
        comps.append(Component("RSI", _clip(s), 0.15, f"RSI(14) = {r:.1f}: {why}."))

    # 4. Bollinger position
    pb = ind.get("bb_pct_b")
    if pb is not None:
        if pb > 1:
            s, why = -0.6, "closed above the upper band (stretched)"
        elif pb < 0:
            s, why = 0.6, "closed below the lower band (stretched)"
        else:
            s, why = 0.0, "inside the bands"
        comps.append(Component("Bollinger Bands", s, 0.10, f"%B = {pb:.2f}; {why}."))

    # 5. Detected patterns
    directional = [p for p in patterns if p.bias != "neutral"]
    if directional:
        net = sum(p.strength * (1 if p.bias == "bullish" else -1) for p in directional)
        names = ", ".join(p.name for p in directional)
        comps.append(Component("Chart patterns", _clip(net), 0.15, f"Detected: {names}."))

    # 6. ML model — only weighted when it beat the naive baseline out-of-sample
    if ml.get("available"):
        skill = ml["skill"]
        weight = 0.20 if skill > 0.02 else 0.0
        s = _clip((ml["prob_up"] - 0.5) * 4)
        reason = (
            f"Estimated P(up over next {ml['horizon_bars']} bars) = {ml['prob_up']:.0%}; "
            f"walk-forward accuracy {ml['oos_accuracy']:.1%} vs {ml['baseline_accuracy']:.1%} baseline."
        )
        if weight == 0.0:
            reason += " Model showed no out-of-sample edge, so it is excluded from the score."
        comps.append(Component("ML direction model", s, weight, reason))

    return comps


def combine(components: list[Component]) -> tuple[str, float, float]:
    active = [c for c in components if c.weight > 0]
    total_w = sum(c.weight for c in active)
    if not active or total_w == 0:
        return "hold", 0.0, 0.0
    score = sum(c.score * c.weight for c in active) / total_w
    action = "buy" if score > BUY_THRESHOLD else "sell" if score < SELL_THRESHOLD else "hold"
    # Agreement: weighted share of components pointing the same way as the score.
    sign = np.sign(score) or 1
    agree = sum(c.weight for c in active if np.sign(c.score) == sign) / total_w
    confidence = min(MAX_CONFIDENCE, 100 * (0.5 * min(1.0, abs(score) / 0.6) + 0.5 * agree) * (0.6 if action == "hold" else 1))
    return action, float(score), float(round(confidence, 1))


def assess_risks(
    ind: dict,
    components: list[Component],
    patterns: list[Pattern],
    ml: dict,
    levels: dict,
    *,
    is_sample: bool,
    stale: bool,
) -> list[dict]:
    risks: list[dict] = []
    close = ind.get("close") or 0
    atr_pct = (ind.get("atr_14") or 0) / close * 100 if close else 0
    if atr_pct > 3:
        risks.append({"level": "high", "title": "High volatility", "detail": f"ATR(14) is {atr_pct:.1f}% of price; stops may be hit by normal noise."})
    elif atr_pct > 1.5:
        risks.append({"level": "medium", "title": "Elevated volatility", "detail": f"ATR(14) is {atr_pct:.1f}% of price."})

    bulls = [c for c in components if c.weight > 0 and c.score > 0.15]
    bears = [c for c in components if c.weight > 0 and c.score < -0.15]
    if bulls and bears:
        risks.append({
            "level": "medium",
            "title": "Conflicting evidence",
            "detail": f"Bullish: {', '.join(c.name for c in bulls)}. Bearish: {', '.join(c.name for c in bears)}.",
        })
    if not ml.get("available"):
        risks.append({"level": "low", "title": "ML model unavailable", "detail": ml.get("reason", "Not enough data.")})
    elif ml["skill"] <= 0.02:
        risks.append({"level": "medium", "title": "No statistical edge", "detail": "The ML model did not beat a naive baseline out-of-sample; this market may be near-random at this horizon."})
    if any(p.name == "Bollinger squeeze" for p in patterns):
        risks.append({"level": "medium", "title": "Volatility expansion likely", "detail": "Compressed bands often precede a sharp move in either direction."})
    vz = ind.get("volume_z")
    if vz is not None and vz < -1:
        risks.append({"level": "low", "title": "Thin volume", "detail": "Below-average volume makes moves less reliable."})
    if close and levels.get("resistances"):
        r = levels["resistances"][0]["price"]
        if (r - close) / close < 0.01:
            risks.append({"level": "low", "title": "Near resistance", "detail": f"Price is within 1% of resistance near {_fmt_price(r)}."})
    if close and levels.get("supports"):
        s = levels["supports"][0]["price"]
        if (close - s) / close < 0.01:
            risks.append({"level": "low", "title": "Near support", "detail": f"Price is within 1% of support near {_fmt_price(s)}."})
    if stale:
        risks.append({"level": "high", "title": "Stale data", "detail": "The live provider was unavailable; analysis used stored candles."})
    if is_sample:
        risks.append({"level": "high", "title": "Sample data", "detail": "This analysis ran on synthetic development data, not real market prices."})
    risks.append({
        "level": "info",
        "title": "Not financial advice",
        "detail": "Signals are model estimates derived from historical data. Markets can move against any signal.",
    })
    return risks
